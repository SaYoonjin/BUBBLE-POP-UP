# ──────────────────────────────────────────────
# UDF: 기사 본문에서 매칭되는 메뉴 추출
# ──────────────────────────────────────────────
@udf(returnType=ArrayType(StringType()))
def extract_menus(article_text):
    """기사 본문에서 키워드 사전 기반으로 매칭되는 메뉴명 리스트를 반환한다.
    키워드가 기사에서 N번 등장하면 해당 메뉴를 N번 카운트한다."""
    if not article_text:
        return []
    matched = []
    for menu_name, keywords in MENU_KEYWORDS.items():
        for kw in keywords:
            count = article_text.count(kw)
            matched.extend([menu_name] * count)
    return matched


# ──────────────────────────────────────────────
# Spark 세션
# ──────────────────────────────────────────────
spark = SparkSession.builder \
    .appName("ETL_News_Score") \
    .config("spark.sql.session.timeZone", "Asia/Seoul") \
    .getOrCreate()

# ──────────────────────────────────────────────
# 1. HDFS에서 1차 정제된 뉴스 Parquet 읽기
# ──────────────────────────────────────────────
df = spark.read.parquet("hdfs://namenode:9000/processed/news/")
print(f"1차 정제 뉴스 로드 완료. 총 {df.count()}건")

# ──────────────────────────────────────────────
# 2. 텍스트 전처리
# ──────────────────────────────────────────────
df_clean = df.withColumn(
    "article_clean",
    trim(regexp_replace(col("article"), r"[^\w\s가-힣a-zA-Z0-9]", " "))
).withColumn(
    "date",
    to_date(col("published"))
)

# ──────────────────────────────────────────────
# 3. 키워드 매칭 → 메뉴 추출
# ──────────────────────────────────────────────
df_with_menus = df_clean.withColumn(
    "matched_menus",
    extract_menus(col("article_clean"))
)

# 매칭된 메뉴가 있는 기사만 필터
from pyspark.sql.functions import size
df_matched = df_with_menus.filter(size(col("matched_menus")) > 0)

print(f"메뉴 키워드 매칭된 기사: {df_matched.count()}건 / 전체 {df.count()}건")

# ──────────────────────────────────────────────
# 4. explode → groupBy(date, menu_name) → count
# ──────────────────────────────────────────────
df_exploded = df_matched.withColumn(
    "menu_name",
    explode(col("matched_menus"))
)

df_mentions = df_exploded.groupBy(
    col("date"),
    col("menu_name"),
).count().withColumnRenamed("count", "mention_count")

# 로그 출력: 날짜별 메뉴별 집계 결과
print("\n=== 날짜별 메뉴 언급량 ===")
df_mentions.orderBy("date", "menu_name").show(100, truncate=False)

# ──────────────────────────────────────────────
# 5. HDFS에 Parquet 저장
# ──────────────────────────────────────────────
df_mentions.write.mode("overwrite").parquet(
    "hdfs://namenode:9000/processed/news_mentions/"
)

total_rows = df_mentions.count()
distinct_dates = df_mentions.select("date").distinct().count()
distinct_menus = df_mentions.select("menu_name").distinct().count()

print(f"\nNews Score ETL 완료.")
print(f"  저장 경로: /processed/news_mentions/")
print(f"  총 행 수: {total_rows}")
print(f"  날짜 수: {distinct_dates}")
print(f"  메뉴 수: {distinct_menus}")

spark.stop()
